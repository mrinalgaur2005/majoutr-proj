class Phase3BenchmarkingEngine:
    """
    Evaluates SVR vs Naive Persistence and ARIMA(2,1,1) baselines across a 15%
    chronological held-out test split, generating metrics and slide graphics.
    """
    def __init__(self, X: pd.DataFrame, y: pd.Series, test_ratio: float = 0.15):
        self.X = X
        self.y = y
        self.test_ratio = test_ratio
        
        split_idx = int(len(X) * (1.0 - test_ratio))
        self.X_train = X.iloc[:split_idx]
        self.X_test = X.iloc[split_idx:]
        self.y_train = y.iloc[:split_idx]
        self.y_test = y.iloc[split_idx:]
        
        self.results = {}

    @staticmethod
    def calculate_metrics(y_true: pd.Series, y_pred: pd.Series) -> dict:
        """Calculates MAPE (%), RMSE (kW), and R2 score on aligned non-NaN pairs."""
        aligned = pd.concat([y_true.rename("true"), y_pred.rename("pred")], axis=1).dropna()
        y_t = aligned["true"]
        y_p = aligned["pred"]
        mape = mean_absolute_percentage_error(y_t, y_p) * 100.0
        rmse = np.sqrt(mean_squared_error(y_t, y_p))
        r2 = r2_score(y_t, y_p)
        return {"MAPE": mape, "RMSE": rmse, "R2": r2}

    def run_benchmarks(self, svr_params: dict | None = None):
        """Fits SVR, ARIMA(2,1,1), and Naive Persistence models on the 15% test set."""
        if svr_params is None:
            svr_params = {"C": 100.0, "gamma": 0.01, "epsilon": 0.05}

        print("    [Phase 3] Fitting SVR (RBF Kernel) Model...")
        print(f"        SVR params: C={svr_params['C']}, gamma={svr_params['gamma']}, epsilon={svr_params['epsilon']}")
        svr_pipeline = Pipeline([
            ('scaler', StandardScaler()),
            ('svr', SVR(
                kernel='rbf',
                C=svr_params["C"],
                gamma=svr_params["gamma"],
                epsilon=svr_params["epsilon"],
            ))
        ])
        svr_pipeline.fit(self.X_train, self.y_train)
        y_pred_svr = pd.Series(svr_pipeline.predict(self.X_test), index=self.y_test.index)

        print("    [Phase 3] Computing Naive Persistence Baseline (y_t = y_{t-1})...")
        y_full = pd.concat([self.y_train, self.y_test])
        y_pred_persist = y_full.shift(1).loc[self.y_test.index]

        print("    [Phase 3] Fitting Parametric ARIMA(2,1,1) Baseline...")
        arima_model = ARIMA(self.y_train, order=(2, 1, 1))
        arima_fit = arima_model.fit()
        arima_forecast = arima_fit.forecast(steps=len(self.y_test))
        y_pred_arima = pd.Series(arima_forecast.values, index=self.y_test.index)

        # Store metrics and predictions
        self.results = {
            "SVR": {
                "pred": y_pred_svr,
                "metrics": self.calculate_metrics(self.y_test, y_pred_svr)
            },
            "Persistence": {
                "pred": y_pred_persist,
                "metrics": self.calculate_metrics(self.y_test, y_pred_persist)
            },
            "ARIMA": {
                "pred": y_pred_arima,
                "metrics": self.calculate_metrics(self.y_test, y_pred_arima)
            }
        }
        return self.results

    def generate_forecast_comparison_plot(self, hours: int = 48, save_path: str = "phase3_forecast_comparison.png"):
        """
        Plots a high-resolution 48-hour time series comparing Actual Load vs SVR, ARIMA, and Persistence.
        """
        slots = hours * 4  # 48 hours x 4 slots/hr = 192 slots
        
        y_true_sub = self.y_test.iloc[:slots]
        y_svr_sub = self.results["SVR"]["pred"].iloc[:slots]
        y_persist_sub = self.results["Persistence"]["pred"].iloc[:slots]
        y_arima_sub = self.results["ARIMA"]["pred"].iloc[:slots]

        fig, ax = plt.subplots(figsize=(12, 5.5), dpi=300)
        
        ax.plot(y_true_sub.index, y_true_sub.values, label="Actual Active Demand (kW)", color="black", linewidth=2.5, linestyle="-")
        ax.plot(y_true_sub.index, y_svr_sub.values, label="SVR Model (RBF Kernel + SLP)", color="#1f77b4", linewidth=2.0, linestyle="-")
        ax.plot(y_true_sub.index, y_persist_sub.values, label="Naive Persistence (y_t-1)", color="#2ca02c", linewidth=1.5, linestyle="--")
        ax.plot(y_true_sub.index, y_arima_sub.values, label="ARIMA(2,1,1) Baseline", color="#d62728", linewidth=1.8, linestyle=":")

        ax.set_title(f"48-Hour Out-of-Sample Load Forecast Comparison (15-Minute Resolution)", fontsize=14, fontweight='bold', pad=15)
        ax.set_ylabel("Active Power Load (kW)", fontsize=12, fontweight='bold')
        ax.set_xlabel("Timestamp", fontsize=12, fontweight='bold')
        ax.grid(True, linestyle=":", alpha=0.6)
        ax.legend(loc="upper right", frameon=True, facecolor="white", framealpha=0.95, fontsize=11, prop={'weight':'bold'})

        plt.tight_layout()
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        plt.close()
        print(f"    [Exported] {save_path}")

    def generate_error_metrics_plot(self, save_path: str = "phase3_error_metrics.png"):
        """
        Generates a grouped bar chart comparing MAPE and RMSE values across SVR, ARIMA, and Persistence.
        """
        models = ["SVR (Proposed)", "Persistence Baseline", "ARIMA(2,1,1) Baseline"]
        mapes = [self.results["SVR"]["metrics"]["MAPE"], self.results["Persistence"]["metrics"]["MAPE"], self.results["ARIMA"]["metrics"]["MAPE"]]
        rmses = [self.results["SVR"]["metrics"]["RMSE"], self.results["Persistence"]["metrics"]["RMSE"], self.results["ARIMA"]["metrics"]["RMSE"]]

        x = np.arange(len(models))
        width = 0.35

        fig, ax1 = plt.subplots(figsize=(10, 5), dpi=300)
        ax2 = ax1.twinx()

        rects1 = ax1.bar(x - width/2, mapes, width, label='MAPE (%)', color='#1f77b4', edgecolor='black')
        rects2 = ax2.bar(x + width/2, rmses, width, label='RMSE (kW)', color='#ff7f0e', edgecolor='black')

        ax1.set_ylabel('MAPE (%)', color='#1f77b4', fontsize=12, fontweight='bold')
        ax2.set_ylabel('RMSE (kW)', color='#ff7f0e', fontsize=12, fontweight='bold')
        ax1.set_title('Out-of-Sample Benchmarking Metrics (15% Chronological Test Set)', fontsize=14, fontweight='bold', pad=15)
        ax1.set_xticks(x)
        ax1.set_xticklabels(models, fontsize=11, fontweight='bold')
        ax1.grid(True, linestyle=':', alpha=0.5, axis='y')

        # Value labels on top of bars
        for rect in rects1:
            height = rect.get_height()
            ax1.annotate(f'{height:.2f}%', xy=(rect.get_x() + rect.get_width() / 2, height),
                         xytext=(0, 3), textcoords="offset points", ha='center', va='bottom', fontweight='bold', color='#1f77b4')

        for rect in rects2:
            height = rect.get_height()
            ax2.annotate(f'{height:.2f} kW', xy=(rect.get_x() + rect.get_width() / 2, height),
                         xytext=(0, 3), textcoords="offset points", ha='center', va='bottom', fontweight='bold', color='#e65100')

        # Combine legends
        lines1, labels1 = ax1.get_legend_handles_labels()
        lines2, labels2 = ax2.get_legend_handles_labels()
        ax1.legend(lines1 + lines2, labels1 + labels2, loc='upper left', frameon=True, facecolor='white', framealpha=0.9, fontsize=11, prop={'weight':'bold'})

        plt.tight_layout()
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        plt.close()
        print(f"    [Exported] {save_path}")


