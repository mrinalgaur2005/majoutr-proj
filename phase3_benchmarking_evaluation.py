class Phase2Visualizer:
    """
    Generates presentation-ready 300+ DPI graphics for Phase 2:
    1. TimeSeriesSplit Chronological CV Diagram (phase2_cv_splits.png)
    2. GridSearch C vs Gamma Heatmap (phase2_hyperparameter_heatmap.png)
    3. 24-Hour Cyclic Time-of-Day Encodings (phase2_cyclic_features.png)
    """

    @staticmethod
    def generate_cv_splits_diagram(n_samples: int = 1000, n_splits: int = 3, save_path: str = "phase2_cv_splits.png"):
        """
        Plots a clean diagram showing the 3 chronological train/validation splits
        generated by TimeSeriesSplit to prove zero look-ahead data leakage.
        """
        tscv = TimeSeriesSplit(n_splits=n_splits)
        fig, ax = plt.subplots(figsize=(10, 4.5), dpi=300)

        indices = np.arange(n_samples)
        for fold, (train_idx, val_idx) in enumerate(tscv.split(indices)):
            # Train bar
            ax.barh(fold, len(train_idx), left=0, color='#1f77b4', edgecolor='black', height=0.5, label='Training Fold' if fold == 0 else "")
            # Validation bar
            ax.barh(fold, len(val_idx), left=len(train_idx), color='#ff7f0e', edgecolor='black', height=0.5, label='Validation Fold' if fold == 0 else "")
            
            # Annotations
            ax.text(len(train_idx) / 2, fold, f"Train ({len(train_idx)})", ha='center', va='center', color='white', fontweight='bold', fontsize=11)
            ax.text(len(train_idx) + len(val_idx) / 2, fold, f"Val ({len(val_idx)})", ha='center', va='center', color='white', fontweight='bold', fontsize=10)

        ax.set_yticks(range(n_splits))
        ax.set_yticklabels([f"Fold {i+1}" for i in range(n_splits)], fontsize=12, fontweight='bold')
        ax.set_xlabel("Time Series Sample Index (Chronological Order)", fontsize=12, fontweight='bold')
        ax.set_title("TimeSeriesSplit (k=3): Chronological CV (Zero Look-Ahead Leakage)", fontsize=14, fontweight='bold', pad=15)
        ax.grid(True, linestyle=':', alpha=0.6, axis='x')
        ax.legend(loc='upper left', frameon=True, facecolor='white', framealpha=0.9, fontsize=11, prop={'weight':'bold'})
        
        plt.tight_layout()
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        plt.close()
        print(f"    [Exported] {save_path}")

    @staticmethod
    def generate_hyperparameter_heatmap(
        cv_results: dict,
        best_params: dict,
        save_path: str = "phase2_hyperparameter_heatmap.png",
    ):
        """
        Builds a 2D validation RMSE heatmap (C vs γ) from Phase 2 GridSearchCV results,
        holding ε fixed at the best value from tuning.
        """
        c_vals = [1.0, 10.0, 100.0]
        gamma_vals = ["scale", 0.1, 0.01]
        best_eps = best_params["svr__epsilon"]
        best_c = best_params["svr__C"]
        best_gamma = best_params["svr__gamma"]

        score_matrix = np.full((len(c_vals), len(gamma_vals)), np.nan)
        for params, neg_rmse in zip(cv_results["params"], cv_results["mean_test_score"]):
            if params["svr__epsilon"] != best_eps:
                continue
            i = c_vals.index(params["svr__C"])
            j = gamma_vals.index(params["svr__gamma"])
            score_matrix[i, j] = -neg_rmse

        gamma_labels = [str(g) for g in gamma_vals]
        df_heat = pd.DataFrame(score_matrix, index=c_vals, columns=gamma_labels)

        fig, ax = plt.subplots(figsize=(8, 5.5), dpi=300)
        sns.heatmap(
            df_heat,
            annot=True,
            fmt=".4f",
            cmap="YlOrRd_r",
            linewidths=0.5,
            linecolor="#333333",
            cbar_kws={"label": "Validation RMSE (kW)"},
            annot_kws={"fontweight": "bold", "fontsize": 12},
            ax=ax,
        )
        cbar = ax.collections[0].colorbar
        cbar.ax.set_ylabel("Validation RMSE (kW)", fontsize=11, fontweight="bold")

        opt_row = c_vals.index(best_c)
        opt_col = gamma_vals.index(best_gamma)
        ax.add_patch(
            plt.Rectangle(
                (opt_col, opt_row),
                1,
                1,
                fill=False,
                edgecolor="#2ca02c",
                lw=4,
                linestyle="-",
            )
        )

        ax.set_title(
            f"SVR Hyperparameter Optimization Grid: RMSE (C vs. γ, ε={best_eps})",
            fontsize=14,
            fontweight="bold",
            pad=15,
        )
        ax.set_xlabel("Kernel Parameter Gamma (γ)", fontsize=12, fontweight="bold")
        ax.set_ylabel("Regularization Parameter C", fontsize=12, fontweight="bold")
        ax.set_xticklabels(ax.get_xticklabels(), fontweight="bold")
        ax.set_yticklabels(ax.get_yticklabels(), fontweight="bold", rotation=0)

        plt.tight_layout()
        plt.savefig(save_path, dpi=300, bbox_inches="tight")
        plt.close()
        print(f"    [Exported] {save_path}")

